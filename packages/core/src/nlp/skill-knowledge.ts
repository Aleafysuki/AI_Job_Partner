export interface KnowledgeResult extends KnowledgeEntry {
  curated: boolean;
  skillName: string;
  flavor: QuestionFlavor;
}

export function knowledgeFor(skillName: string): KnowledgeResult {
  const def = resolveSkill(skillName);
  const name = def?.name ?? skillName;
  const flavor = flavorOf(def?.kind ?? 'domain');
  const curated = CURATED[name];
  if (curated) return { ...curated, curated: true, skillName: name, flavor };
  return { ...FLAVOR_FALLBACK[flavor], curated: false, skillName: name, flavor };
}

/** 已被定制知识库覆盖的技能名单（UI 用来提示「这是通用要点还是定制要点」） */
export function curatedSkillNames(): string[] {
  return Object.keys(CURATED);
}
